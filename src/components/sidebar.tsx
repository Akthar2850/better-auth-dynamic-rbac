export default function Sidebar() {
  const { data: session } = authClient.useSession();
  const pathname = usePathname();
  const role = (session?.user as { role?: string })?.role ?? "endUser";
  const [navItems, setNavItems] = useState<{ top: NavItem[]; bottom: NavItem[] }>({
    top: [],
    bottom: [],
  });

  useEffect(() => {
    async function loadSidebar() {
      try {
        const res = await fetch("/api/sidebar-permissions");
        const { resources } = await res.json();
        setNavItems(getNavItems(resources, role));
      } catch {
        setNavItems(getNavItems([], role));
      }
    }
    if (session) {
      loadSidebar();
    }
  }, [session, role]);

  const { top, bottom } = navItems;

  return (
    <aside className="w-60 bg-sidebar-bg flex flex-col h-full shrink-0">
      <div className="px-5 py-5 border-b border-sidebar-hover">
        <h1 className="text-sidebar-text-active text-lg font-bold tracking-wide">
          Dynamic RBAC
        </h1>
      </div>

      <nav className="flex-1 overflow-y-auto py-3">
        {top.map((item) => {
          const isActive =
            pathname === item.href || pathname.startsWith(item.href + "/");
          return (
            <Link
              key={item.href}
              href={item.href}
              className={`flex items-center gap-3 px-5 py-2.5 text-sm transition-colors ${
                isActive
                  ? "bg-sidebar-active text-sidebar-text-active border-l-3 border-sidebar-text-active"
                  : "text-sidebar-text hover:bg-sidebar-hover hover:text-sidebar-text-active border-l-3 border-transparent"
              }`}
            >
              {icons[item.icon] ?? null}
              <span>{item.label}</span>
            </Link>
          );
        })}
      </nav>

      <div className="border-t border-sidebar-hover py-3">
        {bottom.map((item) => {
          const isActive = pathname === item.href;
          return (
            <Link
              key={item.href}
              href={item.href}
              className={`flex items-center gap-3 px-5 py-2.5 text-sm transition-colors ${
                isActive
                  ? "bg-sidebar-active text-sidebar-text-active border-l-3 border-sidebar-text-active"
                  : "text-sidebar-text hover:bg-sidebar-hover hover:text-sidebar-text-active border-l-3 border-transparent"
              }`}
            >
              {icons[item.icon] ?? null}
              <span>{item.label}</span>
            </Link>
          );
        })}
      </div>
    </aside>
  );
}
